import ExcelJS from "exceljs";
import { saveAs } from "file-saver";
import { isValid } from "date-fns";
import banner from "@/assets/banner.png";
import formattedDate from "../../formattedDate";
import addPOSAnalyticsChart from "./posAnalyticsChart";

const brand = "FFC62828";
const currencyFormat = '"₱"#,##0.00';
const border = Object.fromEntries(["top", "left", "right", "bottom"].map((side) => [side, { style: "thin", color: { argb: "FF000000" } }]));
const overviewBorder = Object.fromEntries(["top", "left", "right", "bottom"].map((side) => [side, { style: "thin", color: { argb: "FFD9D4CE" } }]));
const rankings = [
  ["dishes", "Best-Selling Dishes", "Dish"],
  ["categories", "Sales by Category", "Category"],
];

export async function buildPOSAnalyticsWorkbook({ data, options = {} }) {
  const { date, createdBy = "" } = options;
  if (!isValid(date?.from) || !isValid(date?.to) || date.from > date.to) {
    throw new Error("Please select a valid report period.");
  }
  const workbook = new ExcelJS.Workbook();
  workbook.creator = createdBy;
  workbook.title = "POS Analytics Report";
  workbook.created = new Date();
  let bannerId;
  try {
    const response = await fetch(banner);
    if (!response.ok) throw new Error("Unable to load report banner");
    bannerId = workbook.addImage({ buffer: await response.arrayBuffer(), extension: "png" });
  } catch (error) {
    console.error("Failed to add POS analytics report banner:", error);
  }

  const cellAt = (sheet, row, start, end, value, { heading = false, numFmt, bold = false, size = 12, bordered = true } = {}) => {
    if (start !== end) sheet.mergeCells(row, start, row, end);
    const cell = sheet.getCell(row, start);
    cell.value = value;
    cell.font = { name: "Arial", size, bold: heading || bold, color: { argb: heading ? "FFFFFDF8" : "FF332A21" } };
    cell.border = bordered ? (sheet.name === "Overview" ? overviewBorder : border) : {};
    cell.alignment = { vertical: "middle", horizontal: "left", wrapText: true };
    if (numFmt) cell.numFmt = numFmt;
    if (heading) cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: brand } };
    const text = String(value ?? "");
    const lines = text.split("\n").reduce((sum, part) => sum + Math.max(1, Math.ceil(part.length / ((end - start + 1) * 8))), 0);
    sheet.getRow(row).height = Math.max(sheet.getRow(row).height || 24, heading ? lines * size * 1.2 + 6 : lines * size * 1.4 + 10);
    return cell;
  };
  const addSheet = (name, title, note) => {
    const sheet = workbook.addWorksheet(name, { pageSetup: {
      paperSize: 9, orientation: "portrait", fitToPage: true, fitToWidth: 1, fitToHeight: 0,
      margins: { left: 0.25, right: 0.25, top: 0.4, bottom: 0.4, header: 0.2, footer: 0.2 },
      printTitlesRow: "8:8",
    } });
    sheet.properties.defaultColWidth = 9;
    for (let column = 1; column <= 13; column++) sheet.getColumn(column).width = 9;
    // A narrow blank gutter keeps the M border away from hidden columns/print clipping.
    sheet.getColumn("N").width = 0.5;
    sheet.views = [{ showGridLines: false }];
    sheet.headerFooter.oddFooter = "&LPOS Analytics&RPage &P of &N";
    if (bannerId !== undefined) sheet.addImage(bannerId, { tl: { col: 0, row: 0.05 }, br: { col: 13, row: 4 } });
    const titleCell = cellAt(sheet, 5, 1, 13, title, { bold: true, size: 25 });
    titleCell.font = { bold: true, size: 25 };
    titleCell.alignment.horizontal = "center";
    const subtitleCell = cellAt(sheet, 6, 1, 13, `${formattedDate(date.from)} to ${formattedDate(date.to)}`, { size: 14 });
    subtitleCell.font = { size: 14 };
    subtitleCell.alignment.horizontal = "center";
    subtitleCell.fill = { type: "pattern", pattern: "none" };
    // Match the existing booking transaction export's title/date row heights.
    sheet.getRow(5).height = 40;
    sheet.getRow(6).height = 24;
    if (note) cellAt(sheet, 7, 1, 13, note, { size: 11 });
    return sheet;
  };
  const footer = (sheet, row) => {
    [
      ["Prepared By", createdBy],
      ["Generated By", new Date().toLocaleString("en-US", {
        timeZone: "Asia/Manila", month: "long", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit",
      })],
    ].forEach(([label, value], index) => {
      cellAt(sheet, row + index, 1, 13, {
        richText: [
          { text: `${label}: `, font: { size: 11, bold: true } },
          { text: value, font: { size: 11, bold: false } },
        ],
      }, { size: 11, bordered: false });
      sheet.getRow(row + index).height = 20;
    });
    sheet.pageSetup.printArea = `A1:N${row + 1}`;
  };

  const overview = addSheet("Overview", "POS Analytics Report");
  overview.views = [{ showGridLines: false }];
  overview.pageSetup.printTitlesRow = undefined;
  overview.pageSetup.fitToHeight = 1;
  [
    [1, 4, "Total Sales", data.totalSales, currencyFormat],
    [5, 8, "Total Orders", data.totalOrders, "#,##0"],
    [9, 13, "Average Order Value", data.averageOrderValue, currencyFormat],
  ].forEach(([start, end, label, value, numFmt]) => {
    cellAt(overview, 7, start, end, label, { heading: true });
    cellAt(overview, 8, start, end, value, { numFmt, bold: true, size: 18 });
  });
  cellAt(overview, 10, 1, 13, "Best-Selling Dish", { heading: true });
  cellAt(overview, 11, 1, 13, data.bestSellingDish?.name || "No sales", { bold: true, size: 14 });
  cellAt(overview, 12, 1, 13, `${data.bestSellingDish?.unitsSold ?? 0} units sold`);
  cellAt(overview, 14, 1, 13, "Sales Trends", { heading: true, size: 12 });
  for (let row = 15; row <= 32; row++) overview.getRow(row).height = 20;
  overview.mergeCells("A15:M32");
  footer(overview, 36);

  const trends = addSheet("Sales Trends", "Sales Trends");
  trends.pageSetup.printTitlesRow = "7:7";
  const trendColumns = [[1, 6, "Month"], [7, 10, "Orders", "#,##0"], [11, 13, "Sales", currencyFormat]];
  trendColumns.forEach(([start, end, label]) => cellAt(trends, 7, start, end, label, { heading: true }));
  (data.monthly || []).forEach((month, index) => {
    [month.tooltipLabel || month.month, month.orders, month.value].forEach((value, column) => {
      const [start, end, , numFmt] = trendColumns[column];
      cellAt(trends, index + 8, start, end, value, { numFmt });
    });
  });
  const totalRow = 8 + (data.monthly || []).length;
  ["Total", data.totalOrders, data.totalSales].forEach((value, index) => {
    const [start, end, , numFmt] = trendColumns[index];
    cellAt(trends, totalRow, start, end, value, { bold: true, numFmt });
  });
  footer(trends, totalRow + 3);

  rankings.forEach(([key, title, label]) => {
    const sheet = addSheet(title, title, key === "dishes" ? "Top 5 dishes ranked by quantity sold within the selected period." : "Categories ranked by total POS sales within the selected period.");
    const columns = [[1, 1, "#", "0"], [2, 7, label], [8, 9, "Units Sold", "#,##0"], [10, 11, "Sales", currencyFormat], [12, 13, "Sales Share", "0.0%"]];
    columns.forEach(([start, end, heading]) => cellAt(sheet, 8, start, end, heading, { heading: true }));
    const rows = key === "dishes" ? (data[key] || []).slice(0, 5) : data[key] || [];
    rows.forEach((item, index) => {
      [index + 1, item.name, item.unitsSold, item.value, item.percentage / 100].forEach((value, column) => {
        const [start, end, , numFmt] = columns[column];
        cellAt(sheet, index + 9, start, end, value, { numFmt });
      });
    });
    if (!rows.length) cellAt(sheet, 9, 1, 13, "No POS sales in the selected period.");
    footer(sheet, 11 + Math.max(rows.length, 1));
  });
  return workbook;
}

const posAnalyticsToExcel = async (args) => {
  const workbook = await buildPOSAnalyticsWorkbook(args);
  const { date } = args.options;
  const buffer = await addPOSAnalyticsChart(
    await workbook.xlsx.writeBuffer(),
    args.data.monthly || [],
    args.options.metric === "orders" ? "orders" : "value",
  );
  saveAs(new Blob([buffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }),
    `POS Analytics Report - ${formattedDate(date.from)} to ${formattedDate(date.to)}.xlsx`);
};

export default posAnalyticsToExcel;
